def assess_evidence_confidence(
    sources: list[dict],
    verification_items: list[dict],
) -> dict:
    """Apply fixed, transparent rules before presenting a conclusion."""
    total_claims = len(verification_items)
    supported_claims = sum(
        1
        for item in verification_items
        if str(item.get("status", "")).strip().lower() == "supported"
    )
    support_ratio = supported_claims / total_claims if total_claims else 0.0
    reasons = []

    verified_source_ids = set()

    for item in verification_items:
        if (
            str(item.get("status", "")).strip().lower() != "supported"
            or item.get("quote_verified") is not True
        ):
            continue

        source_proofs = item.get("source_proofs", [])

        if isinstance(source_proofs, list) and source_proofs:
            for proof in source_proofs:
                if not isinstance(proof, dict):
                    continue

                source_id = proof.get("source_id")

                if isinstance(source_id, int) and 1 <= source_id <= len(sources):
                    verified_source_ids.add(source_id)

        else:
            source_id = item.get("proof_source_id")

            if isinstance(source_id, int) and 1 <= source_id <= len(sources):
                verified_source_ids.add(source_id)

    if len(sources) < MIN_SOURCES_FOR_CONCLUSION:
        reasons.append(
            f"only {len(sources)} sources were available "
            f"(minimum: {MIN_SOURCES_FOR_CONCLUSION})"
        )

        if len(verified_source_ids) < 2:
            reasons.append(
                f"only {len(verified_source_ids)} independently quote-verified "
                f"source(s) were available "
                f"(minimum: 2)"
        )
    if total_claims == 0:
        reasons.append("no claims could be verified")
    elif support_ratio < MIN_SUPPORTED_CLAIM_RATIO:
        reasons.append(
            f"{supported_claims}/{total_claims} checked claims were supported "
            f"({support_ratio:.0%}; minimum: {MIN_SUPPORTED_CLAIM_RATIO:.0%})"
        )

    return {
        "should_abstain": bool(reasons),
        "reasons": reasons,
        "supported_claims": supported_claims,
        "total_claims": total_claims,
        "support_ratio": support_ratio,
        "verified_source_count": len(verified_source_ids),
    }

