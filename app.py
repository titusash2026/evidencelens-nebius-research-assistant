def build_retrieval_queries(question: str, research_plan: list[str]) -> list[str]:
    """Use the original question plus the first focused plan questions."""
    queries = []

    for candidate in [question, *research_plan]:
        cleaned = str(candidate).strip()
        if cleaned and cleaned not in queries:
            queries.append(cleaned)

        if len(queries) == MAX_RETRIEVAL_QUERIES:
            break

    return queries


def build_broad_free_query(question: str) -> str:
    """Create a recall-oriented biomedical API query from a long PICO question."""
    stop_words = {
        "a", "an", "and", "are", "as", "at", "by", "can", "compared",
        "compare", "does", "do", "for", "from", "how", "in", "is", "of",
        "on", "or", "should", "than", "that", "the", "this", "to", "vs",
        "versus", "what", "which", "with", "without", "adult", "adults",
        "adolescent", "adolescents", "children", "child", "patients", "patient",
        "people", "years", "year", "evidence", "outcomes", "outcome", "risk",
        "risks", "aged", "age", "older", "younger", "among", "between",
    }
    tokens = re.findall(r"[A-Za-z0-9][A-Za-z0-9+/#.-]*", question.lower())
    keywords: list[str] = []
    for token in tokens:
        cleaned = token.strip(".-")
        if len(cleaned) < 3 or cleaned in stop_words or cleaned in keywords:
            continue
        keywords.append(cleaned)
        if len(keywords) >= 12:
            break
    return " ".join(keywords)


def build_free_retrieval_queries(question: str, research_plan: list[str]) -> list[str]:
    """Combine one broad query with focused lanes for public biomedical APIs.

    PubMed-style APIs retrieve more reliably from focused terms than from a
    full multi-outcome PICO paragraph. The broad lane guarantees recall; the
    planning lanes add precision for trials, reviews, and safety evidence.
    """
    broad_query = build_broad_free_query(question)
    treatment_lanes = build_treatment_queries(question)
    candidates = [
        broad_query,
        f"{broad_query} systematic review guideline".strip(),
        f"{broad_query} clinical trial safety long-term follow-up".strip(),
        *treatment_lanes,
        *research_plan,
        question,
    ]
    queries: list[str] = []
    for candidate in candidates:
        cleaned = " ".join(str(candidate or "").split())
        if cleaned and cleaned not in queries:
            queries.append(cleaned)
        if len(queries) >= 12:
            break
    return queries


def tavily_search_with_timeout(
    tavily_client: TavilyClient,
    search_options: dict,
    timeout_seconds: float | None = None,
) -> dict:
    """Prevent one Tavily request from freezing the full Streamlit run."""
    executor = ThreadPoolExecutor(max_workers=1)
    future = executor.submit(tavily_client.search, **search_options)

    try:
        return future.result(
            timeout=timeout_seconds or TAVILY_REQUEST_TIMEOUT_SECONDS
        )

    except FutureTimeoutError as error:
        future.cancel()
        raise TimeoutError(
            f"Tavily search timed out after "
                f"{timeout_seconds or TAVILY_REQUEST_TIMEOUT_SECONDS} seconds."
        ) from error

    finally:
        executor.shutdown(wait=False, cancel_futures=True)

def retrieve_diverse_candidates(
    tavily_client: TavilyClient | None,
    question: str,
    research_plan: list[str],
    trusted_mode: bool,
) -> tuple[list[dict], dict[str, int], list[str]]:
    """
    Retrieve evidence from independent source groups.
    Each external search has a strict timeout, so the Streamlit app
    never waits indefinitely for Tavily.
    """
    TAVILY_TIMEOUT_SECONDS = 12
    MAX_TAVILY_CALLS = 12

    buckets = (
        build_trusted_retrieval_buckets(question)
        if trusted_mode
        else {"Broad web sources": None}
    )

    source_map = {}
    bucket_counts = {bucket_name: 0 for bucket_name in buckets}
    failed_buckets = []
    search_calls = 0

    if tavily_client is None:
        failed_buckets.append("Tavily (not configured; using free fallback)")

    for retrieval_query in build_retrieval_queries(question, research_plan):
        for bucket_name, domains in buckets.items():
            if tavily_client is None or search_calls >= MAX_TAVILY_CALLS:
                break

            search_options = {
                "query": retrieval_query,
                "search_depth": "advanced",
                "max_results": max(4, TAVILY_RESULTS_PER_QUERY),
                "include_raw_content": "text",
                "timeout": TAVILY_TIMEOUT_SECONDS,
            }

            if domains:
                search_options["include_domains"] = domains

            search_calls += 1

            try:
                search_response = tavily_search_with_timeout(
                    tavily_client=tavily_client,
                    search_options=search_options,
            )
                
            except Exception as exc:
                error_name = type(exc).__name__
                error_text = str(exc).casefold()
                print(
                    f"Tavily failed for {bucket_name}: "
                    f"{error_name}: {exc}",
                    flush=True,
                )
                failed_buckets.append(
                    f"{bucket_name} ({retrieval_query[:45]}...)"
                )
                # A quota/plan denial cannot recover within this run.  Stop
                # immediately and continue with the no-cost public APIs below
                # rather than issuing the remaining Tavily searches.
                if (
                    error_name == "ForbiddenError"
                    or "usage limit" in error_text
                    or "upgrade your plan" in error_text
                ):
                    failed_buckets.append("Tavily quota exhausted; free fallback selected")
                    search_calls = MAX_TAVILY_CALLS
                    break
                continue

            for source in search_response.get("results", []):
                url = str(source.get("url", "")).strip()
                if not url:
                    continue

                if domains and not matches_allowed_domain(url, domains):
                    continue

                source_key = normalise_url(url)
                if source_key in source_map:
                    continue

                source["retrieval_bucket"] = bucket_name
                source_map[source_key] = source
                bucket_counts[bucket_name] += 1

        # active_buckets = sum(count > 0 for count in bucket_counts.values())
        # required_buckets = min(3, len(buckets))

        # if (
        #     len(source_map) >= MIN_SOURCES
        #     and active_buckets >= required_buckets
        # ):
        #     break

        if search_calls >= MAX_TAVILY_CALLS:
            break

    # Biomedical APIs supplement Tavily on every deep-evidence run.  A small
    # Tavily result set must never suppress PubMed/PMC/registry retrieval.
    free_queries = build_free_retrieval_queries(question, research_plan)
    free_sources, free_counts, free_failures = retrieve_free_biomedical_sources(
        queries=free_queries,
        per_source_limit=4,
    )
    print(
        "FREE BIOMEDICAL RETRIEVAL:",
        f"queries={free_queries}",
        f"counts={free_counts}",
        f"failures={free_failures}",
        f"sources={len(free_sources)}",
        flush=True,
    )
    for bucket_name, count in free_counts.items():
        bucket_counts[bucket_name] = bucket_counts.get(bucket_name, 0) + count
    failed_buckets.extend(free_failures)
    for source in free_sources:
        url = str(source.get("url", "")).strip()
        if url:
            source_map.setdefault(normalise_url(url), source)

    return list(source_map.values()), bucket_counts, failed_buckets


def retrieve_fast_candidates(
    tavily_client: TavilyClient | None,
    question: str,
    trusted_mode: bool,
) -> tuple[list[dict], dict[str, int], list[str]]:
    """Retrieve one trusted batch concurrently for the fast-answer path."""
    buckets = (
        build_trusted_retrieval_buckets(question)
        if trusted_mode
        else {"Broad web sources": None}
    )
    bucket_counts = {bucket_name: 0 for bucket_name in buckets}
    failed_buckets: list[str] = []
    source_map: dict[str, dict] = {}

    def search_one_bucket(bucket_name: str, domains: list[str] | None) -> tuple[str, list[str] | None, dict]:
        options = {
            "query": question,
            "search_depth": "advanced",
            "max_results": 4,
            "include_raw_content": "text",
            "timeout": FAST_TAVILY_TIMEOUT_SECONDS,
        }
        if domains:
            options["include_domains"] = domains
        response = tavily_search_with_timeout(
            tavily_client,
            options,
            timeout_seconds=FAST_TAVILY_TIMEOUT_SECONDS,
        )
        return bucket_name, domains, response

    if tavily_client is None:
        failed_buckets.append("Tavily (not configured; using free fallback)")
    else:
        with ThreadPoolExecutor(max_workers=len(buckets)) as executor:
            futures = {
                executor.submit(search_one_bucket, bucket_name, domains): bucket_name
                for bucket_name, domains in buckets.items()
            }
            for future in as_completed(futures):
                bucket_name = futures[future]
                try:
                    completed_bucket, domains, response = future.result()
                except Exception as error:
                    failed_buckets.append(f"{bucket_name} ({type(error).__name__})")
                    continue

                for source in response.get("results", []):
                    url = str(source.get("url", "")).strip()
                    if not url or (domains and not matches_allowed_domain(url, domains)):
                        continue
                    source_key = normalise_url(url)
                    if source_key in source_map:
                        continue
                    source["retrieval_bucket"] = completed_bucket
                    source_map[source_key] = source
                    bucket_counts[completed_bucket] += 1

    # Never let a few web snippets suppress the biomedical evidence providers.
    # Fast mode uses fewer records per lane; Deep mode retrieves richer packets.
    free_sources, free_counts, free_failures = retrieve_free_biomedical_sources(
        queries=build_free_retrieval_queries(question, []),
        per_source_limit=2,
    )
    for bucket_name, count in free_counts.items():
        bucket_counts[bucket_name] = bucket_counts.get(bucket_name, 0) + count
    failed_buckets.extend(free_failures)
    for source in free_sources:
        url = str(source.get("url", "")).strip()
        if url:
            source_map.setdefault(normalise_url(url), source)

    return list(source_map.values()), bucket_counts, failed_buckets


