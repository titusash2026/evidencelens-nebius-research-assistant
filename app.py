def normalise_url(url: str) -> str:
    """Return a stable URL key so repeated Tavily results are merged."""
    parts = urlsplit(url.strip())
    return urlunsplit(
        (
            parts.scheme.lower() or "https",
            parts.netloc.lower().removeprefix("www."),
            parts.path.rstrip("/"),
            "",
            "",
        )
    )


def matches_allowed_domain(url: str, allowed_domains: list[str]) -> bool:
    """Accept a result only when its hostname belongs to its assigned bucket."""
    hostname = urlsplit(str(url).strip()).netloc.lower()
    hostname = hostname.removeprefix("www.").split(":")[0]

    return any(
        hostname == domain or hostname.endswith(f".{domain}")
        for domain in allowed_domains
    )


