def build_controlled_agent() -> tuple[ControlledEvidenceLens, dict]:
    """Connect the generic controller to this app's real tool functions.

    Nemotron is deliberately only used by ``plan_research`` and
    ``extract_evidence``.  Tavily execution, source selection, PICO roles,
    strict quote verification, and release eligibility remain Python decisions.
    """
    artifacts: dict = {}

    def prepare_task(question: str, settings: dict) -> dict:
        return {"question": question, "settings": dict(settings)}

    def plan_research(task: dict, settings: dict) -> dict:
        if settings.get("execution_mode") == "Fast answer (10–15 second target)":
            question = str(task["question"])
            return {
                "search_queries": [question],
                "plan_steps": [
                    "Use the original question as the approved retrieval query.",
                    "Retrieve trusted sources concurrently within the fast budget.",
                    "Synthesize only the bounded, controller-selected evidence packet.",
                ],
                "planning_mode": "python_fast_plan",
            }
        return build_research_task(
            client=nebius_client,
            model=MODEL_NAME,
            question=str(task["question"]),
            settings=settings,
        )

    def retrieve(question: str, plan: dict, settings: dict) -> list[dict]:
        trusted_mode = (
            settings.get("source_policy")
            == "Trusted medical & scientific sources"
        )
        if settings.get("execution_mode") == "Fast answer (10–15 second target)":
            candidates, bucket_counts, failures = retrieve_fast_candidates(
                tavily_client=tavily_client,
                question=question,
                trusted_mode=trusted_mode,
            )
            free_fallback_used = any(
                source.get("retrieval_provider") == "free_biomedical_api"
                for source in candidates
            )
            candidates, identity_audit = enrich_source_identities(candidates)
            candidates, duplicate_audit = deduplicate_sources(candidates)
            ranked = rank_sources(sources=candidates, question=question)
            selected = select_diverse_sources(
                ranked_sources=ranked,
                limit=MAX_FAST_SOURCES,
                max_per_family=4 if free_fallback_used else 2,
            )
            artifacts.update(
                {
                    "fast_mode": True,
                    "free_fallback_used": free_fallback_used,
                    "retrieval_counts": bucket_counts,
                    "retrieval_failures": failures,
                    "identity_audit": identity_audit,
                    "duplicate_audit": duplicate_audit,
                    "bibliographic_audit": {
                        "lookups_attempted": 0,
                        "resolved": 0,
                        "pubmed_resolved": 0,
                        "crossref_resolved": 0,
                        "failed_safe": 0,
                    },
                    "evidence_text_audit": {
                        "pubmed_abstract_enriched": 0,
                        "pubmed_title_match_resolved": 0,
                        "tavily_raw_content_fallback": 0,
                        "retrieval_excerpt_only": 0,
                        "access_gaps_recorded": 0,
                    },
                    "related_evidence_audit": {
                        "seed_pmids_resolved": 0,
                        "related_pmids_discovered": 0,
                        "related_sources_added": 0,
                        "related_lookup_failed_safe": 0,
                    },
                }
            )
            return selected

        candidates, bucket_counts, failures = retrieve_diverse_candidates(
            tavily_client=tavily_client,
            question=question,
            research_plan=(
                plan.get("retrieval_queries")
                or plan.get("search_queries")
                or []
            ),
            trusted_mode=trusted_mode,
        )
        free_fallback_used = any(
            source.get("retrieval_provider") == "free_biomedical_api"
            for source in candidates
        )
        candidates, identity_audit = enrich_source_identities(candidates)
        candidates, duplicate_audit = deduplicate_sources(candidates)
        ranked = rank_sources(sources=candidates, question=question)
        selected = select_diverse_sources(
            ranked_sources=ranked,
            limit=MAX_SOURCES,
            max_per_family=4 if free_fallback_used else 1,
        )
        selected, bibliographic_audit = enrich_bibliographic_metadata(
            sources=selected,
            max_external_lookups=3,
            timeout_seconds=3.0,
        )
        selected, evidence_text_audit = enrich_source_evidence_text(
            selected,
            max_abstract_lookups=8,
            timeout_seconds=4.0,
        )
        related_sources, related_evidence_audit = expand_related_pubmed_sources(
            selected,
            max_seed_sources=3,
            max_related_sources=6,
            timeout_seconds=4.0,
        )
        if related_sources:
            related_sources, _ = enrich_source_identities(related_sources)
            combined_sources, graph_duplicate_audit = deduplicate_sources(
                selected + related_sources
            )
            reranked = rank_sources(sources=combined_sources, question=question)
            selected = select_diverse_sources(
                ranked_sources=reranked,
                limit=MAX_SOURCES,
                max_per_family=4 if free_fallback_used else 2,
            )
            artifacts["graph_duplicate_audit"] = graph_duplicate_audit
        artifacts["retrieval_counts"] = bucket_counts
        artifacts["retrieval_failures"] = failures
        artifacts["free_fallback_used"] = free_fallback_used
        artifacts["identity_audit"] = identity_audit
        artifacts["duplicate_audit"] = duplicate_audit
        artifacts["bibliographic_audit"] = bibliographic_audit
        artifacts["evidence_text_audit"] = evidence_text_audit
        artifacts["related_evidence_audit"] = related_evidence_audit
        return selected

    def triage(question: str, sources: list[dict]) -> tuple[list[dict], list[dict], list[dict]]:
        direct, supplementary, audit = classify_sources_by_pico(
            question=question,
            sources=sources,
        )
        # A trial registry describes the study protocol/status. Keep it as
        # context only; it cannot prove a clinical outcome by itself.
        retained_direct = []
        for source in direct:
            if source.get("evidence_role_hint") != "Supplementary":
                retained_direct.append(source)
                continue
            contextual_source = dict(source)
            contextual_source["pico_status"] = "Supplementary"
            contextual_source["pico_reason"] = (
                "Clinical trial registry record retained as context; it cannot "
                "establish an outcome without published results."
            )
            supplementary.append(contextual_source)
            audit.append(
                {
                    "title": str(contextual_source.get("title", "Untitled source")),
                    "url": str(contextual_source.get("url", "")),
                    "role": "Supplementary evidence",
                    "reason": contextual_source["pico_reason"],
                }
            )
        # A population-relevant article is still not Direct evidence if it
        # studies a treatment the user did not ask to compare.
        return enforce_exact_intervention_match(
            question,
            retained_direct,
            supplementary,
            audit,
        )

    def assess_coverage(question: str, plan: dict, direct_sources: list[dict]) -> dict:
        """Let Python decide whether the evidence packet covers the question."""
        coverage = assess_evidence_coverage(question, plan, direct_sources)
        artifacts["coverage"] = coverage
        return coverage

    def repair_retrieve(
        question: str,
        plan: dict,
        verification: dict,
        attempt: int,
        settings: dict,
    ) -> list[dict]:
        """Retrieve only treatment/outcome lanes the coverage gate found missing."""
        if settings.get("execution_mode") == "Fast answer (10–15 second target)":
            return []
        targeted_queries = build_targeted_coverage_queries(
            question,
            artifacts.get("coverage", {}),
            max_queries=MAX_RETRIEVAL_QUERIES,
        )
        if not targeted_queries:
            return []
        artifacts["coverage_repair_queries"] = targeted_queries
        candidates, repair_counts, repair_failures = retrieve_diverse_candidates(
            tavily_client=tavily_client,
            question=question,
            research_plan=targeted_queries,
            trusted_mode=(settings.get("source_policy") == "Trusted medical & scientific sources"),
        )
        artifacts["coverage_repair_counts"] = repair_counts
        artifacts["coverage_repair_failures"] = repair_failures
        candidates, _ = enrich_source_identities(candidates)
        candidates, _ = deduplicate_sources(candidates)
        ranked = rank_sources(sources=candidates, question=question)
        return select_diverse_sources(ranked, limit=MAX_SOURCES, max_per_family=2)

    def extract_evidence(
        question: str,
        plan: dict,
        direct_sources: list[dict],
        supplementary_sources: list[dict],
    ) -> str:
        # Python prevents a synthesis request when there is not enough direct,
        # independent evidence to support a multi-source answer.
        if len(direct_sources) < 2:
            return (
                "Evidence gap: fewer than two direct sources survived the "
                "retrieval and PICO gates, so no research conclusion was drafted."
            )

        all_sources = direct_sources + supplementary_sources
        is_fast_mode = plan.get("planning_mode") == "python_fast_plan"
        source_limit = MAX_FAST_SOURCES if is_fast_mode else MAX_SOURCES_FOR_SYNTHESIS
        sources = all_sources[:source_limit]
        if is_fast_mode:
            evidence_chars_per_source = max(
                350,
                MAX_FAST_EVIDENCE_PACKET_CHARS // max(len(sources), 1),
            )
        else:
            evidence_chars_per_source = MAX_SYNTHESIS_SOURCE_CHARS
        source_cards, outcome_coverage = build_evidence_packet(
            question,
            sources,
            chars_per_source=evidence_chars_per_source,
        )
        source_context = format_evidence_packet(question, source_cards, outcome_coverage)
        matrix = build_evidence_matrix(question, sources, evidence_chars_per_source)
        source_context += "\n\n" + format_evidence_matrix(matrix)
        artifacts["evidence_matrix"] = matrix
        answer_contract = build_answer_contract(question, sources)
        source_context = source_context + "\n\n" + format_answer_contract(answer_contract)
        artifacts["evidence_packet"] = source_cards
        artifacts["outcome_coverage"] = outcome_coverage
        artifacts["answer_contract"] = answer_contract
        system_prompt = (
            "You are EvidenceLens, a conservative clinical-evidence synthesis assistant. "
            "Use ONLY the supplied source cards and retrieved text. Write a comparison "
            "answer, not a generic summary.\n\n"
            "Mandatory rules:\n"
            "1. Direct sources may support primary conclusions only when their text "
            "supports the exact population and outcome.\n"
            "2. Supplementary sources are context only; label them indirect.\n"
            "3. Never say a source has no extractable data when its card includes "
            "outcome or numerical-result passages.\n"
            "4. Preserve effect estimates exactly; never calculate, combine, or upgrade them.\n"
            "5. For every requested treatment/outcome use: direct evidence, indirect "
            "evidence, conflicting/uncertain evidence, not reported in selected sources, "
            "or evidence not retrieved.\n"
            "6. Cite every factual clinical statement as [Source N].\n"
            "7. Never claim one treatment class proves benefit for another class.\n"
            "8. Do not give patient-specific medical advice.\n"
            "9. Obey the SYNTHESIS POSITIONING CONTRACT exactly. Begin Interpretation "
            "with 'Most-direct evidence' when the contract has most-direct sources and "
            "no exact-direct source for the target population.\n"
            "10. Do not use a source number for more than one title or invent a source identity."
            " 11. Candidate keyword matches are not evidence of an effect. "
            "Distinguish outcome not found in this packet from not reported in the paper. "
            "Break compound findings into separately cited atomic claims. "
            "Do not infer equivalence from a non-significant difference. "
            "Clearly distinguish hypotheses from source-supported findings."
        )
        requested_outcomes = ", ".join(answer_contract.get("requested_outcomes", [])) or "requested outcomes"
        user_prompt = (
            f"{source_context}\n\n"
            "Return Markdown with exactly these sections:\n"
            "## Evidence comparison\n"
            "A compact table: treatment | population applicability | evidence-backed "
            f"findings for {requested_outcomes} | harms/limitations.\n"
            "## Interpretation\n"
            "Separate direct, indirect, uncertain, and missing evidence.\n"
            "## Key limitations\n"
            "Include population mismatch, absent head-to-head evidence, and retrieval limits."
        )

        def synthesize(client: OpenAI, model: str, max_tokens: int) -> str:
            response = client.chat.completions.create(
                model=model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=0.2,
                max_tokens=max_tokens,
                extra_body={"chat_template_kwargs": {"enable_thinking": False}},
            )
            draft = (response.choices[0].message.content or "").strip()
            if not draft:
                raise RuntimeError(f"{model} returned an empty candidate synthesis.")
            return draft

        if not is_fast_mode:
            draft = synthesize(nebius_client, MODEL_NAME, 1400)
            artifacts["synthesis_model"] = MODEL_NAME
            artifacts["synthesis_route"] = "primary"
            return draft

        # Strict Nemotron-only circuit breaker.  Do not substitute a different
        # model when Nemotron is unavailable.
        try:
            draft = synthesize(fast_nemotron_client, MODEL_NAME, 700)
            artifacts["synthesis_model"] = MODEL_NAME
            artifacts["synthesis_route"] = "nemotron_only"
            return draft
        except Exception as nemotron_error:
            artifacts["nemotron_synthesis_error"] = (
                f"{type(nemotron_error).__name__}: {nemotron_error}"
            )
            artifacts["synthesis_model"] = MODEL_NAME
            artifacts["synthesis_route"] = "nemotron_unavailable"
            # An empty draft forces the controller to release only its evidence
            # availability summary rather than mislabelling a fallback as an answer.
            return ""

    def verify(question: str, draft: str, sources: list[dict]) -> dict:
        if len(sources) and artifacts.get("fast_mode"):
            return {
                "overall_summary": "Fast-mode citation and source-availability gate completed.",
                "verification_items": [],
                "entailment_audit": [],
            }
        if sum(source.get("pico_status") == "Direct" for source in sources) < 2:
            return {
                "overall_summary": "No conclusion: insufficient direct evidence.",
                "verification_items": [],
                "entailment_audit": [],
            }
        return verify_claims(
            client=nebius_client,
            model=VERIFIER_MODEL,
            question=question,
            answer=draft,
            sources=sources,
        )

    return (
        ControlledEvidenceLens(
            prepare_task=prepare_task,
            plan_research=plan_research,
            retrieve=retrieve,
            triage=triage,
            extract_evidence=extract_evidence,
            verify=verify,
            assess_coverage=assess_coverage,
            repair_retrieve=repair_retrieve,
            policy=ControllerPolicy(
                max_retrieval_queries=MAX_RETRIEVAL_QUERIES,
                max_sources=MAX_SOURCES,
                max_repairs=1,
                min_verified_claims_for_full_release=1,
            ),
        ),
        artifacts,
    )

